/**
 * CORE CRM app icon.
 * Loaded from iconUrl in deployEnvConfig (e.g. /icons/app-core-crm.png).
 * Falls back to a placeholder if the file is not yet added.
 */
function AppIconCoreCrm() {
  const cfg = MODEL_APPS.find(a => a.key === 'core-crm');
  if (cfg?.iconUrl) {
    return <img src={resolveIconUrl(cfg.iconUrl)} alt="" className="app-card-icon-img" />;
  }
  return (
    <svg viewBox="0 0 100 100" aria-hidden="true" focusable="false" className="app-card-svg-icon">
      <rect x="10" y="10" width="80" height="80" rx="12" fill="currentColor" opacity="0.35" />
      <text x="50" y="62" textAnchor="middle" fill="currentColor" fontSize="32" fontWeight="bold">C</text>
    </svg>
  );
}

