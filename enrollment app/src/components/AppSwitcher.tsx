// ── Static app config ────────────────────────────────────────────────────────
// Model app names/IDs and canvas app IDs are all environment-specific.
// They come from deployEnvConfig.ts, regenerated by post-deploy-powerapps.ps1.
type ModelAppConfig = { key: string; displayName: string; appModuleId: string; iconUrl?: string };
const MODEL_APPS = DEPLOY_ENV.modelApps as unknown as ModelAppConfig[];

// Canvas app IDs are environment-specific; they come from deployEnvConfig.ts which is
// regenerated by post-deploy-powerapps.ps1 for each target environment.
const CANVAS_APPS = [
  { key: 'change-management', displayName: 'Change Management' },
] as const;

function resolveCanvasUrl(key: string): string | null {
  const ids = DEPLOY_ENV.canvasAppIds as Record<string, string>;
  const appId = ids[key];
  if (!appId || appId.startsWith('replace-with-')) return null;
  return `https://apps.powerapps.com/play/e/${DEPLOY_ENV.environmentId}/a/${appId}?tenantId=${DEPLOY_ENV.tenantId}&hidenavbar=true`;
}

type AppType = 'model' | 'canvas' | 'code' | 'external';

interface ResolvedApp {
  key: string;
  displayName: string;
  type: AppType;
  url: string | null;
  isCurrent: boolean;
}

// ── URL helpers ──────────────────────────────────────────────────────────────
function normalizeOrgUrl(url: string | null | undefined): string | null {
  const trimmed = url?.trim();
  if (!trimmed) return null;
  return trimmed.replace(/\/main\.aspx.*$/i, '').replace(/\/?$/, '/');
}

function isActiveConfig(value: unknown): boolean {
  if (value === true || value === 1) return true;
  if (typeof value === 'string') {
    const n = value.trim().toLowerCase();
    return n === 'true' || n === '1' || n === 'yes';
  }
  return false;
}

async function resolveFarmsUrl(): Promise<string | null> {
  // Fetch all fields (no select) and try all known prefix/case variants,
  // matching the same logic used by EnrolmentCalculationPage.getFarmsLegacyBaseUrl().
  const result = await Vsi_armsconfigurationsService.getAll({
    maxPageSize: 50,
    orderBy: ['modifiedon desc'],
  });
  const rows = result.data ?? [];
  for (const row of rows) {
    const r = row as unknown as Record<string, unknown>;
    const url = (
      (typeof r['cr2a9_FARMSURLNEW'] === 'string' && r['cr2a9_FARMSURLNEW'].trim()) ||
      (typeof r['cr2a9_farmsurlnew'] === 'string' && r['cr2a9_farmsurlnew'].trim()) ||
      (typeof r['cr4dd_FARMSURLNEW'] === 'string' && r['cr4dd_FARMSURLNEW'].trim()) ||
      (typeof r['cr4dd_farmsurlnew'] === 'string' && r['cr4dd_farmsurlnew'].trim())
    ) || null;
    if (url) return url;
  }
  return null;
}

async function resolveOrgUrl(): Promise<string | null> {
  const cached = getCoreConfig().dataverseOrgUrl;
  if (cached) return cached;

  const result = await Vsi_armsconfigurationsService.getAll({
    maxPageSize: 50,
    select: ['vsi_activeconfiguration', 'vsi_coreenvironmenturl'],
    orderBy: ['modifiedon desc'],
  });
  const rows = result.data ?? [];
  const active = rows.find(r =>
    isActiveConfig((r as unknown as Record<string, unknown>).vsi_activeconfiguration) &&
    r.vsi_coreenvironmenturl?.trim()
  );
  const row = active ?? rows.find(r => r.vsi_coreenvironmenturl?.trim());
  return normalizeOrgUrl(row?.vsi_coreenvironmenturl);
}

// ── Icons ────────────────────────────────────────────────────────────────────
// Icons are looked up via ICON_ASSET_URLS so Vite processes them into dist/assets/
// (ensuring npx power-apps push includes them in the deployed bundle).
function resolveIconUrl(url: string): string {
  return ICON_ASSET_URLS[url] ?? `${import.meta.env.BASE_URL}${url.replace(/^\//, '')}`;
}
