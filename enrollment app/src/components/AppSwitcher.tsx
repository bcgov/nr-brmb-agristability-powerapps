function AppIcon({ type, appKey }: { type: AppType; appKey: string }) {
  if (appKey === 'core-crm') return <AppIconCoreCrm />;
  if (appKey === 'finance') return <AppIconFinance />;
  const appIcons = DEPLOY_ENV.appIcons as Record<string, string>;
  const iconUrl = appIcons[appKey];
  if (iconUrl) return <img src={resolveIconUrl(iconUrl)} alt="" className="app-card-icon-img" />;
  if (type === 'code') return <EnrolmentSvgIcon />;
  if (type === 'canvas') return <Layers size={36} />;
  if (type === 'external') return <Globe size={36} />;
  return <LayoutDashboard size={36} />;
}

// ── Card ─────────────────────────────────────────────────────────────────────
function AppCard({ app }: { app: ResolvedApp }) {
  const typeLabelMap: Record<AppType, string> = {
    model:    'UNIFIED INTERFACE',
    canvas:   'CANVAS',
    code:     'CODE APP',
    external: 'WEB APP',
  };

  const content = (
    <>
      <div className="app-card-icon-area">
        <AppIcon type={app.type} appKey={app.key} />
      </div>
      <div className="app-card-body">
        <span className="app-card-name">{app.displayName}</span>
        <span className={`app-card-badge app-card-badge--${app.type}`}>
          {typeLabelMap[app.type]}
        </span>
      </div>
    </>
  );

  const cls = `app-card${app.isCurrent ? ' app-card--current' : ''}`;

  if (app.url && !app.isCurrent) {
    return (
      <a href={app.url} target="_blank" rel="noopener noreferrer" className={cls} title={`Open ${app.displayName}`}>
        {content}
      </a>
    );
  }
  return <div className={cls}>{content}</div>;
}

// ── Main component ───────────────────────────────────────────────────────────
export function AppSwitcher({ onClose }: { onClose: () => void }) {
  const [apps, setApps] = useState<ResolvedApp[]>(() => [
    ...MODEL_APPS.map(c => ({
      key: c.key,
      displayName: c.displayName,
      type: 'model' as AppType,
      url: null,
      isCurrent: false,
    })),
    { key: 'enrollment-app', displayName: 'Enrolment App', type: 'code' as AppType, url: null, isCurrent: true },
    ...CANVAS_APPS.map(c => ({ key: c.key, displayName: c.displayName, type: 'canvas' as AppType, url: resolveCanvasUrl(c.key), isCurrent: false })),
    { key: 'farms', displayName: 'FARMS', type: 'external' as AppType, url: null, isCurrent: false },
  ]);

  useEffect(() => {
    let cancelled = false;

    async function resolve() {
      // Resolve model-driven URLs from org URL + known app module IDs.
      // Note: appmodules/canvasapps/webresourceset are blocked by the Dataverse connector
      // so canvas URLs are hardcoded in CANVAS_APPS config above.
      const orgUrl = await resolveOrgUrl().catch(() => null);
      if (!cancelled && orgUrl) {
        setApps(prev => prev.map(app => {
          const cfg = MODEL_APPS.find(c => c.key === app.key);
          if (cfg) return { ...app, url: `${orgUrl}main.aspx?appid=${cfg.appModuleId}` };
          return app;
        }));
      }

      // Resolve FARMS URL from Dataverse config
      const farmsUrl = await resolveFarmsUrl().catch(() => null);
      if (!cancelled && farmsUrl) {
        setApps(prev => prev.map(app =>
          app.key === 'farms' ? { ...app, url: farmsUrl } : app
        ));
      }
    }

    void resolve();
    return () => { cancelled = true; };
  }, []);

  const handleClose = useCallback(() => onClose(), [onClose]);

  // Close on Escape
  useEffect(() => {
    const handler = (e: KeyboardEvent) => { if (e.key === 'Escape') handleClose(); };
    window.addEventListener('keydown', handler);
    return () => window.removeEventListener('keydown', handler);
  }, [handleClose]);

  return (
    <div
      className="app-switcher-backdrop"
      onClick={handleClose}
      role="dialog"
      aria-modal="true"
      aria-label="App switcher"
    >
      <div className="app-switcher-panel" onClick={e => e.stopPropagation()}>
        <div className="app-switcher-header">
          <h2 className="app-switcher-title">Apps</h2>
          <button
            className="app-switcher-close"
            onClick={handleClose}
            aria-label="Close app switcher"
            type="button"
          >
            <X size={20} />
          </button>
        </div>
        <div className="app-switcher-grid">
          {apps.map(app => (
            <AppCard key={app.key} app={app} />
          ))}
        </div>
      </div>
    </div>
  );
}
